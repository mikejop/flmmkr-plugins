#!/usr/bin/env python3
"""Inlines local #include "..." files (fc_shared.h, palette_generated.h) into kernels/falsecolor.metal
and emits a C++ raw-string header, because the kernel is compiled at runtime from a string.
Usage: embed_metal.py <falsecolor.metal> <project root> <out.h>"""
import os
import re
import sys

kernel, root, out = sys.argv[1:4]
seen = set()

def inline(path):
    text = open(path, encoding="utf-8").read()
    def repl(m):
        inc = os.path.join(root, m.group(1))
        if inc in seen:
            return ""
        seen.add(inc)
        return inline(inc)
    return re.sub(r'^#include\s+"([^"]+)"\s*$', repl, text, flags=re.M)

src = inline(kernel)
assert 'MSL_END)"' not in src
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/embed_metal.py. Do not edit.\n#pragma once\n")
    f.write('static const char* const kFalseColorMetalSource = R"MSL_END(\n' + src + ')MSL_END";\n')
