#!/usr/bin/env python3
"""Inlines palette_generated.h into kernels/falsecolor.metal and emits a C++ raw-string header.
Usage: embed_metal.py <falsecolor.metal> <palette_generated.h> <out.h>"""
import re
import sys

kernel, palette, out = sys.argv[1:4]
src = open(kernel, encoding="utf-8").read()
pal = open(palette, encoding="utf-8").read()
src = re.sub(r'#include\s+"palette_generated\.h"', lambda m: pal, src)
assert 'MSL_END)"' not in src
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/embed_metal.py. Do not edit.\n#pragma once\n")
    f.write('static const char* const kFalseColorMetalSource = R"MSL_END(\n' + src + ')MSL_END";\n')
